// システムプロンプトの組み立て。
//
// 役割: BASE プロンプト（役割・基本方針）に、各ツールソースのスキル（Markdown 文字列）を連結する。
//       スキルは src/agent/skills/*.js に 1 ドメイン 1 ファイルで置き、tools/sources.js の各ソースが
//       自分のスキルを宣言する。このモジュールは tools/ を import しない（結線は hooks/useAgentSession.js）。
// 関係: hooks/useAgentSession.js が composeSystemPrompt() を安定プレフィックス（キャッシュ対象）として使う。
//       スキル文字列は決定的にする（現在日時などの揮発情報は system-context.js の揮発ブロックで渡す）。

export const BASE_SYSTEM_PROMPT = `あなたはブラウザ上で動く、ツールを使って作業するアシスタントです。利用者の自然言語の指示を受けて、与えられたツールを組み合わせて調べ・計算し・結果を分かりやすく報告します。

## 基本方針
- ユーザーへの応答は必ず日本語で行う（コード・ID・固有名詞などの識別子は原文のまま）。
- 数値や事実を答えるときは必ずツールの結果を根拠にし、推測しない。前提・単位・対象を明記する。
- ツールのエラーは観測し、メッセージのヒントに従って入力や条件を修正して再試行する（同じ失敗を繰り返さない。3 回失敗したら原因と代替案を説明する）。
- 大きな結果を会話に持ち込まない。必要な部分だけを取り出して要約する。
- 何をしたか・何が分かったかを最後に 2〜4 行でまとめる。
- 日付の扱い: 現在日時は system の「## 現在日時」に与えられる。ユーザーが指定した日付・期間は、自分の学習時点の知識から「未来だから存在しない」と判断してはならない。相対表現（今日・先月・直近 1 年）は「## 現在日時」を基準に解釈する。

## 利用可能ツール
使えるツールとその使い方は、この後に続く各スキルに書かれている。`

export function composeSystemPrompt({ base = BASE_SYSTEM_PROMPT, skills = [] } = {}) {
  return [base, ...skills]
    .map((p) => String(p ?? '').trim())
    .filter(Boolean)
    .join('\n\n---\n\n')
}
